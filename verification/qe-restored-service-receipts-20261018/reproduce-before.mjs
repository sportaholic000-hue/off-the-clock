import '../../test/pricebookTestEnv.mjs';
import test from 'node:test';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {reconcilePricebook,pricebookPayload} from '../../client/src/pricebookConflict.js';
import {setup,editLocal,deleteRemote,save,read} from './fixture.mjs';

test('exact base reproduces real HTTP 400 after restoring server-owned adoption receipt',async t=>{
  assert.equal(execFileSync('git',['rev-parse','HEAD'],{encoding:'utf8'}).trim(),'c1817621f6eccb31822979bf994efc4902682d34');
  assert.equal(execFileSync('git',['diff','HEAD','--','client/src/pricebookConflict.js'],{encoding:'utf8'}),'');
  const f=await setup(t),base=f.original,local=editLocal(base),remote=await deleteRemote(f,base);
  const stale=await save(f,local);assert.equal(stale.status,409);
  const conflict=reconcilePricebook(base,local,remote);assert.equal(conflict.unresolved.length,1);assert.equal(conflict.conflicts[0].kind,'remote_deleted');
  const merged=reconcilePricebook(base,local,remote,{[conflict.conflicts[0].key]:'local'});
  const payload=pricebookPayload(merged.draft);
  assert.equal(payload.services[0].id,undefined);assert.ok(payload.services[0].startingValueAdoptions);
  const result=await save(f,payload);assert.equal(result.status,400);assert.equal(result.body.error,'Creation and approval receipts are generated by the server.');
  assert.deepEqual((await read(f)).services,[]);
  console.log(JSON.stringify({base:'c1817621f6eccb31822979bf994efc4902682d34',staleStatus:stale.status,restoreStatus:result.status,error:result.body.error,localLaborDollars:payload.services[0].pricing.laborPerSqft.vinyl_plank,leakedReceipt:payload.services[0].startingValueAdoptions,servicesPersisted:0}));
});
