git('merge-base','--is-ancestor',gate.mergeCommit,'HEAD');
assert.match(gate.verifiedSourceCommit,/^[a-f0-9]{40}$/);
git('merge-base','--is-ancestor',gate.verifiedSourceCommit,'HEAD');
