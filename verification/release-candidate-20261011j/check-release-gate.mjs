import assert from 'node:assert/strict';
import fs from 'node:fs';
import {execFileSync} from 'node:child_process';
const folder='verification/release-candidate-20261011j/';
const gate=JSON.parse(fs.readFileSync(folder+'RELEASE_GATE.json','utf8'));
const git=(...args)=>execFileSync('git',args,{encoding:'utf8'}).trim();
assert.equal(process.env.GITHUB_REF,'refs/heads/claude/release-candidate-20261011j');
assert.equal(git('rev-parse','HEAD'),process.env.GITHUB_SHA);
assert.equal(gate.tag,'rc-20261011j');
